import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { connectors, type ConnectorName } from "../src/_connectors.ts";
import {
  capabilityLabels,
  connectorCapabilities,
} from "./_capabilities-data.ts";
import type { DatabaseCapabilities } from "../src/types.ts";

const outputFile = fileURLToPath(
  new URL("../docs/1.guide/_capabilities-table.md", import.meta.url),
);

const check = "✓";
const cross = "—";

/** Canonical connector names, in registry order, with aliases removed. */
function canonicalConnectorNames(): ConnectorName[] {
  const seen = new Set<string>();
  return (Object.keys(connectors) as ConnectorName[]).filter((name) => {
    const subpath = connectors[name];
    if (seen.has(subpath)) {
      return false;
    }
    seen.add(subpath);
    return true;
  });
}

/** Pads `value` to `width`, matching how Prettier lays out markdown tables. */
function pad(value: string, width: number, align: "left" | "center"): string {
  const total = width - [...value].length;
  if (align === "left") {
    return value + " ".repeat(total);
  }
  const left = Math.floor(total / 2);
  return " ".repeat(left) + value + " ".repeat(total - left);
}

function generateTable(names: ConnectorName[]): string {
  const keys = Object.keys(capabilityLabels) as (keyof DatabaseCapabilities)[];
  const headers = ["Connector", ...Object.values(capabilityLabels)];

  // The connector column reads as a label, the flag columns as marks.
  const aligns = headers.map((_, index) =>
    index === 0 ? ("left" as const) : ("center" as const),
  );

  const body = names.map((name) => [
    name,
    ...keys.map((key) => (connectorCapabilities[name][key] ? check : cross)),
  ]);

  // `:-:` is the narrowest legal separator, so it sets the minimum column width.
  const widths = headers.map((header, index) =>
    Math.max(
      3,
      ...[header, ...body.map((row) => row[index]!)].map(
        (cell) => [...cell].length,
      ),
    ),
  );

  const separator = widths.map((width, index) =>
    aligns[index] === "left"
      ? ":" + "-".repeat(width - 1)
      : ":" + "-".repeat(width - 2) + ":",
  );

  const rows = [headers, separator, ...body].map((row, index) =>
    index === 1
      ? `| ${row.join(" | ")} |`
      : `| ${row
          .map((cell, column) => pad(cell, widths[column]!, aligns[column]!))
          .join(" | ")} |`,
  );

  return rows.join("\n");
}

const content = `<!-- Auto-generated by scripts/gen-capabilities-docs.ts. Do not edit manually. -->

${generateTable(canonicalConnectorNames())}
`;

await writeFile(outputFile, content, "utf8");
console.log("Generated capabilities table to", outputFile);
